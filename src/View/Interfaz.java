    private void jButtonRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonRegistrarActionPerformed
        // TODO add your handling code here:
        
        String TipoEnvio = jComboBoxEnvio.getSelectedItem().toString();

        if(TipoEnvio.equalsIgnoreCase("Empaque")){
            
                try{
             int Items = Integer.parseInt(jTextFieldItems.getText());
        int PrecioEnvio = Integer.parseInt(jTextFieldPrecioItem.getText());
        
        if (Items <= 0 || PrecioEnvio <= 0){
            
            JOptionPane.showMessageDialog(null, "Ingrese valores mayores a 0");
            return;
        
        }
             chareableController.registrarPackaging(Items, PrecioEnvio);

                } catch(NumberFormatException ex){
                    JOptionPane.showMessageDialog(null,"Ingrese valores numericos");
                }
        JOptionPane.showMessageDialog(null,
        chareableController.mostrarResultados());
        
      } else if(TipoEnvio.equalsIgnoreCase("Bicicleta")){
            
       try{
          double kms = Double.parseDouble(jTextFieldKMS.getText());
          
          if(kms <= 0){
               JOptionPane.showMessageDialog(null,"ingrese kilometros mayores a 0");
               return;
          }
          String codigoBici = "BICI-" + ContadorBici;
          
           chareableController.registrarBikeDelivery(codigoBici, kms);
           ContadorBici++;
            JOptionPane.showMessageDialog(null, "Codigo generado: " + codigoBici);
            
       }  catch(NumberFormatException ex){
           JOptionPane.showMessageDialog(null,"ingrese kilometros válidos");
           return;
       }
             
        } else if(TipoEnvio.equalsIgnoreCase("Furgoneta")){
            try{
                double kms = Double.parseDouble(jTextFieldKMS.getText());
                
                if(kms <= 0){
               JOptionPane.showMessageDialog(null,"ingrese kilometros mayores a 0");
               return;
          }
            String codigoVan = "VAN-" + ContadorVan;    
                chareableController.registrarVanDelivery(codigoVan, kms);
                ContadorVan++;
                
                JOptionPane.showMessageDialog(null, "Codigo generado: " + codigoVan);
            } catch (NumberFormatException ex){
                JOptionPane.showMessageDialog(null,"ingrese kilometros válidos");
                
            }
                
                }
         
        
         
         String resultados = chareableController.mostrarResultados();
         double total = chareableController.calcularTotalGeneral();
         
         JOptionPane.showMessageDialog(null, resultados + " \n Total" + total);
         
         
         
         
         
         
    }//GEN-LAST:event_jButtonRegistrarActionPerformed

